/**
 * Release signing is read from keystore.properties at the repository root, which is not in version
 * control. The release build still runs when that file is missing, it just produces an unsigned
 * APK, so anyone can build from source without holding a signing key.
 *
 * Paths inside keystore.properties are relative to the repository root.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        keystorePropertiesFile.inputStream().use { load(it) }
    }
}

android {
    namespace = "com.panelstash"
    // Current AndroidX artifacts require compiling against API 37.
    compileSdk = 37

    defaultConfig {
        applicationId = "com.panelstash"
        minSdk = 26
        targetSdk = 36
        versionCode = 4
        versionName = "0.2"

        ksp {
            arg("room.schemaLocation", "$projectDir/schemas")
        }
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                storeFile = rootProject.file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            // Null when keystore.properties is absent, which leaves the APK unsigned.
            signingConfig = signingConfigs.findByName("release")
        }
    }

    buildFeatures {
        compose = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
}

